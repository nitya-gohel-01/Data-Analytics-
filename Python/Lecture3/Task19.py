# Sum of N Numbers 

num_of_attempts = int(input("Enter the number of attempts : "))

sum = 0

for i in range(1,num_of_attempts+1):
    
    sum += i
    
print('sum = ',sum)
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    